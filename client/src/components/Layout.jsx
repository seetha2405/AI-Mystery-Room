import { useEffect, useState } from 'react';
import { Link } from 'react-router-dom';
import { Fingerprint } from 'lucide-react';
import { apiConfigurationError } from '../api/client.js';
export function Layout({ children }) {
  const [serverWaking, setServerWaking] = useState(false);
  useEffect(() => {
    const updateWaking = (event) => setServerWaking(event.detail);
    window.addEventListener('server-waking-change', updateWaking);
    return () => window.removeEventListener('server-waking-change', updateWaking);
  }, []);

  return (
    <div className="app-shell">
      <header className="nav">
        <Link to="/" className="brand">
          <span className="brand-mark">
            <Fingerprint size={20} />
          </span>
          <span>
            AI Mystery <b>Room</b>
          </span>
        </Link>
        <nav className="nav-actions" aria-label="Main navigation">
          <Link className="nav-link" to="/cases">
            Case files
          </Link>
          <Link className="nav-link" to="/create">
          New mystery <span aria-hidden="true">↗</span>
          </Link>
        </nav>
      </header>
      {apiConfigurationError ? (
        <main className="wrap page-wrap api-config-error" role="alert">
          <section className="card">
            <h1>Server configuration needed</h1>
            <p>{apiConfigurationError}</p>
          </section>
        </main>
      ) : (
        <>
          {serverWaking && (
            <div className="server-waking" role="status" aria-live="polite">
              The server is waking up, this can take up to a minute
            </div>
          )}
          {children}
        </>
      )}
      <footer className="footer">
        <span>AI MYSTERY ROOM</span>
        <span>Fictional content generated by AI · All cases are invented</span>
      </footer>
    </div>
  );
}
